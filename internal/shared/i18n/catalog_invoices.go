// exemptionCodeNumbers is the pinned AT list as of 2026 (the same list as
// invoices/domain.ExemptionCodes; a test in the invoices templates package
// keeps them in step): M01-M16, M19-M26, M30-M46 and M99.
func exemptionCodeNumbers() []int {
	var out []int
	for _, r := range [][2]int{{1, 16}, {19, 26}, {30, 46}, {99, 99}} {
		for n := r[0]; n <= r[1]; n++ {
			out = append(out, n)
		}
	}
	return out
}

// exemptionMessages builds the invoices.exemption.Mxx keys. generic is the
// language's text for a code without a known reference, e.g. "VAT exemption
// reason"; prefix is used with a reference.
func exemptionMessages(generic string) map[MessageKey]string {
	out := map[MessageKey]string{}
	for _, n := range exemptionCodeNumbers() {
		code := "M" + strconv.Itoa(n/10) + strconv.Itoa(n%10)
		text := generic + " " + code
		if ref := exemptionRefs[n]; ref != "" {
			text += " (" + ref + ")"
		}
		out["invoices.exemption."+MessageKey(code)] = text
	}
	return out
}

func mergeMessages(maps ...map[MessageKey]string) map[MessageKey]string {
	out := map[MessageKey]string{}
	for _, m := range maps {
		for k, v := range m {
			out[k] = v
		}
	}
	return out
}

