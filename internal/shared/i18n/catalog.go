// T returns the message for key in lang. If the key is missing in lang it
// falls back to the English value (FR-009). If the key is missing everywhere
// it returns the key itself; the catalog completeness test guards against
// that ever happening in practice.
func T(lang Language, key MessageKey) string {
	return lookup(catalog, lang, key)
}

// lookup resolves key within msgs for lang, falling back to the English
// catalog when the key is missing in the requested language (FR-009). The
// gap is recorded with a warning so missing translations are corrected.
func lookup(msgs map[Language]map[MessageKey]string, lang Language, key MessageKey) string {
	if m, ok := msgs[lang]; ok {
		if s, ok := m[key]; ok {
			return s
		}
	}
	slog.Warn("missing translation, falling back to English", "lang", lang, "key", key)
	if en, ok := msgs[LanguageEN]; ok {
		if s, ok := en[key]; ok {
			return s
		}
	}
	return string(key)
}
